def decompose_core_pack(P_in, W_known=None, K_known=None):
    """Strip outer full-height upright columns (unless W_known/K_known given) and decompose into (core, bars, U_L, U_R, W_core, K_src)."""
    a = np.array(P_in, dtype=np.float64)
    h = 0.5 * (np.abs(np.cos(a[:, 2])) + np.abs(np.sin(a[:, 2])))
    a[:, 0] -= (a[:, 0] - h).min()
    a[:, 1] -= (a[:, 1] - h).min()
    ang = a[:, 2] - (math.pi / 2.0) * np.round(a[:, 2] / (math.pi / 2.0))
    tl = np.abs(ang) > 0.025
    if int(tl.sum()) < 40:
        return None
    pos_frac = float((ang[tl] > 0).mean())
    if 0.18 < pos_frac < 0.82:
        return None
    if pos_frac < 0.5:
        Lx0 = float((a[:, 0] + h).max())
        a = np.column_stack([Lx0 - a[:, 0], a[:, 1], -ang])
        ang = a[:, 2]
        tl = np.abs(ang) > 0.025
    if np.ptp(a[tl, 0]) > np.ptp(a[tl, 1]):
        a = np.column_stack([a[:, 1], a[:, 0], -ang])
        if float((a[tl, 2] > 0).mean()) < 0.5:
            Lx1 = float((a[:, 0] + h).max())
            a = np.column_stack([Lx1 - a[:, 0], a[:, 1], -a[:, 2]])
    else:
        a[:, 2] = ang

    h = 0.5 * (np.abs(np.cos(a[:, 2])) + np.abs(np.sin(a[:, 2])))
    a[:, 0] -= (a[:, 0] - h).min()
    a[:, 1] -= (a[:, 1] - h).min()
    if W_known is not None and K_known is not None:
        core = a.copy()
        W_core = int(W_known)
        K_src = int(K_known)
    else:
        K_src = math.isqrt(len(a))
        tl = np.abs(a[:, 2]) > 0.025
        tx0 = float((a[tl, 0] - h[tl]).min())
        tx1 = float((a[tl, 0] + h[tl]).max())
        L_x = float((a[:, 0] + h).max())
        n_left = max(0, int(math.floor(tx0 + 0.08)))
        n_right = max(0, int(math.floor((L_x - tx1) + 0.08)))
        up = ~tl
        keep = np.ones(len(a), dtype=bool)
        if n_left > 0:
            keep &= ~(up & (a[:, 0] < n_left + 0.05))
        if n_right > 0:
            keep &= ~(up & (a[:, 0] > L_x - n_right - 0.05))
        core = a[keep].copy()
        hc = 0.5 * (np.abs(np.cos(core[:, 2])) + np.abs(np.sin(core[:, 2])))
        core[:, 0] -= (core[:, 0] - hc).min()
        core[:, 1] -= (core[:, 1] - hc).min()
        W_core = K_src - n_left - n_right
    if W_core < 8:
        return None

    tl_c = np.abs(core[:, 2]) > 0.025
    med_th = float(np.median(core[tl_c, 2]))
    c, s = math.cos(med_th), math.sin(med_th)
    t_idx = np.where(tl_c)[0]
    v = -core[tl_c, 0] * s + core[tl_c, 1] * c
    ord_v = np.argsort(v)
    v_s = v[ord_v]
    sp = np.where(np.diff(v_s) > 0.35)[0]
    st = np.concatenate([[0], sp + 1])
    en = np.concatenate([sp + 1, [len(v_s)]])
    bars = [
        core[t_idx[ord_v[b0:b1]]][np.argsort(core[t_idx[ord_v[b0:b1]], 0])]
        for b0, b1 in zip(st, en)
        if (b1 - b0) >= 2
    ]
    if len(bars) < 12:
        return None
    poly = np.polyfit(core[tl_c, 1], core[tl_c, 0], 1)
    u_idx = np.where(~tl_c)[0]
    is_left = core[u_idx, 0] < (poly[0] * core[u_idx, 1] + poly[1])
    U_L = core[u_idx[is_left]]
    U_R = core[u_idx[~is_left]]
    return core, bars, U_L, U_R, W_core, K_src


def apply_one_zigzag(core_in, add_flag, step_bars, W_known=None, K_known=None):
    """Apply 1 zigzag splice of `step_bars` in {1, 2, 4, 5} on `core_in`."""
    dec = decompose_core_pack(core_in, W_known=W_known, K_known=K_known)
    if dec is None:
        return []
    core, bars, U_L, U_R, W_core, K_src = dec
    nb = len(bars)
    # Pick best interior matching pair (b_lo, b_lo + step_bars) closest to center with minimal deviation!
    best_pair = None
    mid_b = nb // 2
    for b_lo in range(4, nb - step_bars - 3):
        b_hi = b_lo + step_bars
        if len(bars[b_lo]) != len(bars[b_hi]) or len(bars[b_lo]) < 6:
            continue
        dv = bars[b_hi][:, :2] - bars[b_lo][:, :2]
        vec = np.mean(dv, axis=0)
        dev = float(np.abs(dv - vec).max())
        dw = int(round(-vec[0]))
        dh = int(round(vec[1]))
        if dw not in (0, 1) or dh < 1 or dev > 0.14:
            continue
        score = dev + 0.004 * abs(b_lo - mid_b)
        if best_pair is None or score < best_pair[0]:
            best_pair = (score, b_lo, b_hi, vec, dw, dh)
    if best_pair is None:
        return []

    _, b_lo, b_hi, vec, dw, dh = best_pair
    y_L_lo = float(round(float(bars[b_lo][0, 1]) - 0.5))
    y_L_hi = y_L_lo + float(dh)
    y_R_lo = float(round(float(bars[b_lo][-1, 1]))) + 0.5
    y_R_hi = y_R_lo + float(dh)

    if add_flag:
        sh1 = np.array([float(dw), 0.0, 0.0])
        sh2 = np.array([float(dw) + vec[0], vec[1], 0.0])
        T1 = np.vstack(bars[:b_hi]) + sh1
        T2 = np.vstack(bars[b_lo:]) + sh2
        UL1 = U_L[U_L[:, 1] < y_L_hi] + sh1
        UL2 = U_L[U_L[:, 1] >= y_L_lo] + sh2
        UR1 = U_R[U_R[:, 1] < y_R_hi] + sh1
        UR2 = U_R[U_R[:, 1] >= y_R_lo] + sh2
        extras = []
        if dw == 1:
            n_yl = int(round(y_L_lo + vec[1]))
            for j in range(max(0, n_yl)):
                extras.append([0.5, j + 0.5, 0.0])
            if len(U_R) > 0:
                x_rmax = float(U_R[:, 0].max()) + float(dw)
                y_cur = float(U_R[:, 1].max()) + vec[1]
                while y_cur > y_R_hi - 0.1:
                    extras.append([x_rmax, y_cur, 0.0])
                    y_cur -= 1.0
        parts = [T1, T2, UL1, UL2, UR1, UR2]
        if extras:
            parts.append(np.array(extras, dtype=np.float64))
        Qc = E.to_origin(np.vstack(parts))
        out_res = [(Qc, W_core + dw, K_src + dh, f"add{step_bars}")]
        # If len(Qc) is 1 or 2 above target (W_new*K_new + excess_src), also emit exact-trimmed variant!
        ex_src = len(core) - W_core * K_src
        want_len = (W_core + dw) * (K_src + dh) + ex_src
        diff = len(Qc) - want_len
        if diff in (1, 2) and len(UR2) > diff:
            # Drop `diff` lowest-y squares of UR2 (right at the splice seam!)
            ur2_ord = np.argsort(UR2[:, 1])
            UR2_trim = UR2[ur2_ord[diff:]]
            p2 = [T1, T2, UL1, UL2, UR1, UR2_trim]
            if extras:
                p2.append(np.array(extras, dtype=np.float64))
            out_res.append(
                (
                    E.to_origin(np.vstack(p2)),
                    W_core + dw,
                    K_src + dh,
                    f"add{step_bars}x",
                )
            )
        return out_res
    else:
        if dw != 0 or K_src - dh < 16:
            return []
        sh2 = np.array([-vec[0], -vec[1], 0.0])
        T1 = np.vstack(bars[:b_lo])
        T2 = np.vstack(bars[b_hi:]) + sh2
        UL1 = U_L[U_L[:, 1] < y_L_lo]
        UL2 = U_L[U_L[:, 1] >= y_L_hi] + sh2
        UR1 = U_R[U_R[:, 1] < y_R_lo]
        UR2 = U_R[U_R[:, 1] >= y_R_hi] + sh2
        Qc = E.to_origin(np.vstack([T1, T2, UL1, UL2, UR1, UR2]))
        out_res = [(Qc, W_core, K_src - dh, f"del{step_bars}")]
        ex_src = len(core) - W_core * K_src
        want_len = W_core * (K_src - dh) + ex_src
        miss = want_len - len(Qc)
        if miss in (1, 2):
            # Keep `miss` seam upright squares from U_R[y_R_lo <= y < y_R_hi] shifted halfway!
            seam_ur = U_R[(U_R[:, 1] >= y_R_lo) & (U_R[:, 1] < y_R_hi)]
            if len(seam_ur) >= miss:
                keep_ur = seam_ur[:miss].copy()
                keep_ur[:, :2] += 0.5 * sh2[:2]
                Qc_ex = E.to_origin(np.vstack([T1, T2, UL1, UL2, UR1, UR2, keep_ur]))
                out_res.append((Qc_ex, W_core, K_src - dh, f"del{step_bars}x"))
        return out_res


def pad_and_heal_core(Qc, W_new, K_new, cur_L_map):
    """Pad (K_new - W_new) full-height upright columns, relax seam with Numba L-BFGS, compact & adjust +-1/2!"""
    out = []
    if not (18 <= K_new <= 31) or W_new > K_new:
        return out
    n_pad = K_new - W_new
    n_left = n_pad // 2
    n_right = n_pad - n_left

    hc = 0.5 * (np.abs(np.cos(Qc[:, 2])) + np.abs(np.sin(Qc[:, 2])))
    Qc0 = Qc.copy()
    Qc0[:, 0] -= (Qc0[:, 0] - hc).min()
    Qc0[:, 1] -= (Qc0[:, 1] - hc).min()
    w_act = float((Qc0[:, 0] + hc).max())
    h_act = float((Qc0[:, 1] + hc).max())

    S_nom = max(float(K_new) + 0.505, w_act + float(n_pad) + 0.015, h_act + 0.015)
    # Build padded array
    cols = []
    for i in range(n_left):
        for j in range(K_new):
            cols.append([i + 0.5, j + 0.5, 0.0])
    Q_shift = Qc0.copy()
    Q_shift[:, 0] += float(n_left) + 0.004
    for i in range(n_right):
        x_c = float(n_left) + w_act + 0.508 + i
        for j in range(K_new):
            cols.append([x_c, j + 0.5, 0.0])
    P_raw = np.vstack([Q_shift, np.array(cols, dtype=np.float64)]) if cols else Q_shift
    n_raw = len(P_raw)
    if not (320 <= n_raw <= 1000):
        return out

    all_free = np.ones(n_raw, dtype=np.bool_)
    healed = None
    for dS_try in (0.015, 0.055, 0.110):
        P_sc = E.to_origin(P_raw)
        cur_sp = float(E.side(P_sc))
        S_try = max(float(K_new) + 0.505, min(cur_sp, float(K_new) + 0.56)) + dS_try
        if cur_sp > S_try - 0.004:
            fac = (S_try - 0.02) / max(cur_sp, 1e-9)
            P_sc[:, :2] = 0.5 * S_try + (P_sc[:, :2] - 0.5 * cur_sp) * fac
        Qr, en = E.relax(P_sc, all_free, float(S_try), 1600, 1e-19)
        if en < 1e-15:
            sing = w49a.build_singles_w49(Qr, max_singles=460)
            Qc2, Sc2, ov = E.Compactor(Qr, singles=sing).compact(
                max_iter=120, patience=3
            )
            if ov <= 2e-9 and E.min_gap(Qc2) >= -1e-8:
                try:
                    xs, ys, ts, _ = SLP.polish(
                        Qc2[:, 0],
                        Qc2[:, 1],
                        Qc2[:, 2],
                        iters=85,
                        r0=2.5e-3,
                        rmin=1e-10,
                        tol_sep=-1e-13,
                        time_limit=10.0,
                    )
                    Qs = w32a.safe_open(np.column_stack([xs, ys, ts]))
                    Ss = float(E.side(Qs))
                    if Ss < Sc2 and E.min_gap(Qs) >= -1e-10:
                        Qc2, Sc2 = Qs, Ss
                except Exception:
                    pass
                healed = (Qc2.astype(np.float64), float(Sc2))
                break

    if healed is None:
        return out

    Qh, Sh = healed
    nh = len(Qh)
    if nh in cur_L_map and Sh < cur_L_map[nh] + 0.032:
        out.append((nh, Sh, f"w{W_new}", Qh))

    # Also hit K_new^2 + 1 / +2 via 1- or 2-square skeleton deletion if nh is +1 or +2 above!
    for d_del in (1, 2):
        nt = nh - d_del
        if nt < 320 or nt not in cur_L_map:
            continue
        if d_del == 1:
            cands = w44h._skeleton_and_band_indices(Qh, max_idx=16)
            best_d = None
            for idx in cands[:10]:
                try:
                    Qd, Sd = w32a.fast_delete_and_compact(Qh, idx)
                    if Qd is not None and (best_d is None or Sd < best_d[0]):
                        best_d = (float(Sd), Qd.astype(np.float64))
                except Exception:
                    continue
            if best_d is not None and best_d[0] < cur_L_map[nt] + 0.030:
                out.append((nt, best_d[0], f"w{W_new}d1", best_d[1]))
        elif d_del == 2 and nt == K_new * K_new + 1:
            # 2-step quick delete specifically when targeting K^2 + 1!
            cands1 = w44h._skeleton_and_band_indices(Qh, max_idx=8)
            best_1 = None
            for idx in cands1[:5]:
                try:
                    Qd1, Sd1 = w32a.fast_delete_and_compact(Qh, idx)
                    if Qd1 is not None and (best_1 is None or Sd1 < best_1[0]):
                        best_1 = (Sd1, Qd1)
                except Exception:
                    continue
            if best_1 is not None:
                cands2 = w44h._skeleton_and_band_indices(best_1[1], max_idx=8)
                best_2 = None
                for idx2 in cands2[:5]:
                    try:
                        Qd2, Sd2 = w32a.fast_delete_and_compact(best_1[1], idx2)
                        if Qd2 is not None and (best_2 is None or Sd2 < best_2[0]):
                            best_2 = (float(Sd2), Qd2.astype(np.float64))
                    except Exception:
                        continue
                if best_2 is not None and best_2[0] < cur_L_map[nt] + 0.030:
                    out.append((nt, best_2[0], f"w{W_new}d2", best_2[1]))
    return out


def generate_splices_for_donor(args_tuple):
    src_n, P_src, cur_L_map = args_tuple
    dec0 = decompose_core_pack(P_src)
    if dec0 is None:
        return []
    core0, _, _, _, W0, K0 = dec0

    # Generate 1-step and 2-step spliced cores!
    stage1 = []
    for add_f, sb in [
        (True, 4),
        (True, 5),
        (True, 1),
        (True, 2),
        (False, 1),
        (False, 2),
    ]:
        for Qc, Wn, Kn, tg in apply_one_zigzag(
            core0, add_f, sb, W_known=W0, K_known=K0
        ):
            stage1.append((Qc, Wn, Kn, f"z{src_n}_{tg}"))

    stage2 = list(stage1)
    only_s2 = []
    # Chain 2nd step on V4/V5 widened cores to reach ALL intermediate K values!
    for Qc1, W1, K1, tg1 in stage1:
        if "add4" in tg1 or "add5" in tg1:
            for add2, sb2 in [(False, 1), (False, 2), (True, 1), (True, 2), (True, 4)]:
                for Qc2, W2, K2, tg2 in apply_one_zigzag(
                    Qc1, add2, sb2, W_known=W1, K_known=K1
                ):
                    it2 = (Qc2, W2, K2, f"{tg1}_{tg2}")
                    stage2.append(it2)
                    only_s2.append(it2)

    # Chain 3rd step to unlock W=16 on K=27,28,29 (730,785,842) AND W=17 on K=29,30,31 (842,901,962)!
    for Qc2, W2, K2, tg2 in only_s2:
        if K2 >= 29:
            for add3, sb3 in [(False, 1), (False, 2), (True, 4)]:
                for Qc3, W3, K3, tg3 in apply_one_zigzag(
                    Qc2, add3, sb3, W_known=W2, K_known=K2
                ):
                    stage2.append((Qc3, W3, K3, f"{tg2}_{tg3}"))
                    if sb3 == 4 and K3 >= 32:
                        for Qc4, W4, K4, tg4 in apply_one_zigzag(
                            Qc3, False, 2, W_known=W3, K_known=K3
                        ):
                            stage2.append((Qc4, W4, K4, f"{tg2}_{tg3}_{tg4}"))

    results = []
    seen = set()
    for Qc, Wn, Kn, tg in stage2:
        if not (18 <= Kn <= 31) or Wn > Kn:
            continue
        key_ck = (Wn, Kn, len(Qc))
        if key_ck in seen:
            continue
        seen.add(key_ck)
        try:
            for nt, St, wtag, Qt in pad_and_heal_core(Qc, Wn, Kn, cur_L_map):
                results.append((nt, St, f"{tg}_{wtag}", Qt))
        except Exception:
            continue
    return results


def worker_polish_staircase(job):
    n, L0, Q_init, tag_in, seed, sa_sec, quench_sec, wide_sec, deadline = job
    out_tag, st, cS, res = w49a.run_fault_open_pipeline(
        Q_init, L0, seed, sa_sec, quench_sec, wide_sec, deadline, tag_prefix=tag_in
    )
    return n, out_tag if res is not None else tag_in, st, cS - L0, res


